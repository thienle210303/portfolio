#!/usr/bin/env node
/**
 * Writes design/system/tokens.css: a mirror of the tokens in
 * src/app/globals.css for the design boards under design/ (round 25).
 *
 * The boards are plain HTML and cannot import a Tailwind source file, so they
 * read this instead. It is generated, never edited: change globals.css, run
 * `pnpm design:tokens`, and tests/lib/design-tokens.test.ts fails until the
 * committed file matches. The site imports nothing from design/.
 *
 * What is mirrored: the palette and the motion/tracking `@theme` blocks, and
 * the stretch of `@layer base` from the type steps to `.tone-contrast` (the
 * steps and spacing, both themes, the paper scope and the three tones).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

// Relative to the working directory, like tests/lib/scenery.test.ts: both
// `pnpm design:tokens` and vitest run from the repo root, and under vitest's
// jsdom environment `import.meta.url` is not a file URL.
const SOURCE = path.resolve("src/app/globals.css");
const TARGET = path.resolve("design/system/tokens.css");

/** The three faces next/font loads in src/app/layout.tsx, by their real names. */
const FONTS = {
  "--font-sans": '"Bricolage Grotesque", ui-sans-serif, system-ui, sans-serif',
  "--font-display": '"Bricolage Grotesque", ui-sans-serif, system-ui, sans-serif',
  "--font-mono": '"Courier Prime", ui-monospace, Menlo, monospace',
  "--font-serif": '"Newsreader", Georgia, serif',
};

/** The body of the block whose opening brace is the first `{` at or after `from`. */
function blockAt(css, from) {
  const open = css.indexOf("{", from);
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === "{") depth += 1;
    if (css[i] === "}" && (depth -= 1) === 0) return { body: css.slice(open + 1, i), end: i + 1 };
  }
  throw new Error("design-tokens: unbalanced braces in globals.css");
}

const tidy = (text, indent = "  ") =>
  text
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => indent + line)
    .join("\n");

/** Re-indent a run of rules by their brace depth. */
function rules(text) {
  let depth = 0;
  return text
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      if (line.startsWith("}")) depth -= 1;
      const out = "  ".repeat(Math.max(depth, 0)) + line;
      if (line.endsWith("{")) depth += 1;
      return out;
    })
    .join("\n");
}

/** Index of the first line that starts (after indentation) with `text`, from `from`. */
function lineStart(css, text, from = 0) {
  const pattern = new RegExp(`^[ \\t]*${text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`, "m");
  const match = pattern.exec(css.slice(from));
  if (!match) throw new Error(`design-tokens: globals.css no longer has "${text}"`);
  return from + match.index;
}

export function buildTokens(css = readFileSync(SOURCE, "utf8")) {
  // Line starts only: the file's comments quote `@theme {` in prose.
  const palette = blockAt(css, lineStart(css, "@theme {"));
  const motion = blockAt(css, lineStart(css, "@theme {", palette.end));

  const base = lineStart(css, "@layer base {");
  const start = lineStart(css, ":root {", base);
  const last = blockAt(css, lineStart(css, ".tone-contrast {", start));

  const fonts = Object.entries(FONTS)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");

  return [
    "/* GENERATED by scripts/design-tokens.mjs from src/app/globals.css. Do not edit:",
    "   change globals.css and run `pnpm design:tokens`. */",
    "",
    "/* Palette (first @theme block). Boards style against the aliases below, not these. */",
    ":root {",
    tidy(palette.body),
    "}",
    "",
    "/* Motion and tracking (second @theme block). */",
    ":root {",
    tidy(motion.body),
    "}",
    "",
    "/* Fonts: the faces src/app/layout.tsx loads through next/font. */",
    ":root {",
    fonts,
    "}",
    "",
    "/* Type steps, spacing, both themes, the paper scope and the three tones (@layer base). */",
    rules(css.slice(start, last.end)),
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(path.dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, buildTokens());
  console.log("Wrote design/system/tokens.css");
}

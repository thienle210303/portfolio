import { chromium } from '@playwright/test';
const OUT = '/tmp/claude-0/-home-user-portfolio/625391a5-3e1d-50a1-9382-08424c01ebd1/scratchpad';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const errs = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
p.on('console', m => { if (m.type()==='error') errs.push('CONSOLE ' + m.text().slice(0,160)); });
await p.goto('http://localhost:3000', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
const cat = p.getByRole('button', { name: /quick actions/ });
await p.mouse.move(700, 300); await p.waitForTimeout(2200);
await cat.screenshot({ path: `${OUT}/f-sit.png` });
await p.mouse.move(1250, 700); await p.waitForTimeout(140);
await cat.screenshot({ path: `${OUT}/f-walk.png` });
await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/f-page.png` });
await cat.click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/f-menu.png` });
await b.close();
console.log(errs.length ? errs.join('\n') : 'no errors');
